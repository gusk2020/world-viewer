// Recomputes the adopted design's 南西諸島 east–west corrections and writes src/adopted-offsets.js.
// Usage: node tools/fit_ryukyu.mjs
import fs from "node:fs"; import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const C = require("../src/core.js"), geo = require("../data/ship-geo.json");
const model = C.buildModel(geo);
const s = C.presetState(model, "adopted"); s.terrain.islandOffsetsKm = {};
const r = C.resolveRyukyu(model, s, (name, dx) => console.log(`move ${name} ${dx.toFixed(4)} km`));
const off = r.state.terrain.islandOffsetsKm;
fs.writeFileSync(new URL("../src/adopted-offsets.js", import.meta.url), `// Generated by tools/fit_ryukyu.mjs — 採用基準案の南西諸島 東西補正（ship km）。空 = 補正不要。\nwindow.SHIP_ADOPTED_OFFSETS = ${JSON.stringify(off)};\n`);
console.log(`moved ${r.moved.length} islands`, off);
